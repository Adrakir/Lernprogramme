"""Exercise the interactive stations, differentiated handoff and local reflection."""
import os
from pathlib import Path
from urllib.parse import urlsplit
from playwright.sync_api import sync_playwright, expect

url = Path('../MatheKompass.html').resolve().as_uri()
with sync_playwright() as pw:
    engine = os.getenv('MATHE_BROWSER', 'chromium')
    browser = getattr(pw, engine).launch(executable_path=os.getenv('CHROMIUM_PATH') or None)
    page = browser.new_page(viewport={'width':390,'height':844})
    page.set_default_timeout(5000)
    errors=[]
    page.on('pageerror', lambda exc: errors.append(str(exc)))
    def station(id):
        page.goto(url+'?aufgabe='+id+'#atelier')
        expect(page.get_by_role('heading',name='Mathe-Atelier')).to_be_visible()
    def click(label):
        page.get_by_role('button',name=label,exact=True).click()
    def number(label,value):
        form=page.locator('form').filter(has=page.get_by_label(label))
        form.get_by_role('textbox').fill(str(value))
        form.get_by_role('button').click()
        expect(form.get_by_role('status')).to_contain_text('Richtig')
    def slider(label,value):
        control=page.get_by_role('slider',name=label,exact=True)
        control.focus()
        control.press('Home')
        for _ in range(value-int(control.get_attribute('min'))):
            control.press('ArrowRight')
    station('lineal')
    slider('Linke Messmarke',34)
    slider('Rechte Messmarke',91)
    number('Wie lang ist der Stift?', '5,7')
    station('dose')
    click('Dose leeren');click('Auf null stellen');click('Dose füllen')
    expect(page.locator('output')).to_have_text('710 g')
    number('Die volle Dose',710);number('Eine zweite volle Dose',160)
    station('fahrplan')
    number('Wie viel Zeit liegt',6);click('15:19')
    expect(page.get_by_text('Der erste erreichbare Bus',exact=False)).to_contain_text('15:06')
    station('buch')
    page.get_by_label('Was schätzt du').fill('20');click('Schätzung festhalten')
    page.get_by_label('Gemessene Breite').fill('19,2');page.get_by_label('Gemessene Höhe').fill('25')
    expect(page.get_by_role('status')).to_contain_text('8 mm')
    station('band')
    click('2 m 5 cm');click('2,05 m');click('Paar prüfen')
    expect(page.get_by_role('status')).to_contain_text('Richtig')
    station('ueberschlag')
    click('155');click('1055');click('Überschlag prüfen');number('Rechne jetzt genau',655)
    station('ziffern')
    for a in range(2,10):
        page.get_by_label('Zehner der ersten Zahl').fill(str(a))
        page.get_by_label('Zehner des Ergebnisses').fill(str(a-2))
        click('Paar prüfen')
    expect(page.get_by_text('8 von 8 möglichen Paaren gefunden.')).to_be_visible()
    station('waage')
    slider('Fehlender Summand',35)
    expect(page.get_by_text('Links: 55.',exact=False)).to_contain_text('Gleichgewicht!')
    station('trick')
    click('Addition untersuchen');click('Subtraktion')
    expect(page.get_by_role('status')).to_contain_text('Abstand')
    station('probe')
    for k in ['278','+','225','=','503']: click(k)
    click('Probe auswerten');expect(page.get_by_role('status')).to_contain_text('bestätigt')
    click('Zahlendreher einbauen')
    for k in ['252','+','278','=','503']: click(k)
    click('Probe auswerten');expect(page.get_by_role('status')).to_contain_text('530')
    station('fehlt')
    click('Das kann ich noch nicht wissen');click('Wie lange fährt er?');click('9:02 Uhr')
    station('markieren')
    click('8:15 Uhr');click('45 Minuten');click('Markierung prüfen')
    expect(page.get_by_role('status')).to_contain_text('9:00')
    click('Frage wechseln');click('6 € pro Kind');click('24 Kinder');click('Markierung prüfen')
    expect(page.get_by_role('status')).to_contain_text('144')
    station('zettel')
    click('Wie viel Saft brauchen alle Kinder zusammen?');number('Zwischenergebnis',6000)
    number('6.000 ml in Litern',6);number('Wie viele Flaschen',4)
    station('rueckwaerts')
    number('Von den verbliebenen',9);number('Wie teuer war',3);number('Probe vorwärts',4)
    station('wege')
    number('Gehzeit zu Fuß',10);number('Gesamtzeit mit Bus',11)
    page.get_by_label('Ankunft zu Fuß').fill('15:10');page.get_by_label('Ankunft mit Bus').fill('15:11')
    click('Ankunftszeiten prüfen');page.get_by_label('Welchen Weg').select_option('Mit dem Bus')
    page.get_by_label('Was spricht').fill('Ich bin kürzer im Regen.')
    station('mission')
    page.get_by_label('Weg zum Bahnhof').select_option('1')
    page.get_by_label('Wie viele Minuten').fill('54');click('Antwort prüfen')
    page.get_by_label('Gepäck auswählen').select_option('1')
    page.get_by_label('Wie viel Gewicht').fill('6');click('Antwort prüfen')
    page.get_by_label('Flaschen einpacken').select_option('8');click('Plan prüfen')
    expect(page.get_by_role('status')).to_contain_text('überschritten')
    click('Gepäck ändern');page.get_by_label('Gepäck auswählen').select_option('0')
    page.get_by_label('Wie viel Gewicht').fill('8');click('Antwort prüfen')
    page.get_by_label('Flaschen einpacken').select_option('8');click('Plan prüfen')
    expect(page.get_by_role('status')).to_contain_text('Der Plan funktioniert')
    station('hilfen')
    number('28 + 17',45);click('Ähnliche Aufgabe mit weniger Hilfe')
    page.get_by_label('Plättchen',exact=True).uncheck()
    click('Mit diesen Hilfen starten')
    number('38 + 17',55)
    expect(page.get_by_text('Heute hast du den Übertrag ohne Plättchen gefunden.')).to_be_visible()
    page.goto(url+'#unterricht')
    page.get_by_text('Unterrichtsaufgabe per Link oder QR-Code',exact=True).click()
    page.get_by_label('Busankunft').select_option('54')
    page.get_by_label('Gehzeit in Minuten').select_option('4')
    for level in [1,2,3]:
        page.get_by_label('Hilfestufe').select_option(str(level))
        link=urlsplit(page.get_by_label('Link zum Teilen').input_value())
        assert link.fragment=='atelier'
        expect(page.get_by_role('img',name='QR-Code zur gewählten Unterrichtsaufgabe')).to_be_visible()
        child=browser.new_page()
        child.goto(url+'?'+link.query+'#'+link.fragment)
        expect(child.get_by_role('heading',name='Den Anschluss erreichen')).to_be_visible()
        expect(child.locator('caption')).to_have_text('Fahrplan am Schulzentrum')
        expect(child.locator('.atelier-zeit')).to_have_count(0 if level==3 else 1)
        expect(child.get_by_text('14:54',exact=True)).to_be_visible()
        assert child.evaluate("localStorage.getItem('mathe-kompass-lernbelege-v1')") is None
        child.close()
    page.goto(url+'#familie')
    page.get_by_text('Meine Lernwoche · Rückschau',exact=True).click()
    page.get_by_label('Eine gelöste Aufgabe').select_option(index=1)
    page.get_by_label('Früher war schwierig').fill('Den Übertrag merken.')
    page.get_by_label('Jetzt achte ich auf').fill('Die Einer ergeben einen Zehner.')
    click('Rückblick speichern')
    page.reload();page.get_by_text('Meine Lernwoche · Rückschau',exact=True).click()
    expect(page.get_by_text('Jetzt achte ich auf: Die Einer ergeben einen Zehner.')).to_be_visible()
    assert not errors,errors
    browser.close()
print(engine, 'Atelierstationen, Hilfestufen, Teilungslink und Lernrückschau geprüft.')
