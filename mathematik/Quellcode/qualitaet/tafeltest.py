"""Test the classroom models and retry feedback using touch and keyboard."""
import os
import re
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = Path('../MatheKompass.html').resolve().as_uri()
with sync_playwright() as pw:
    engine = os.getenv('MATHE_BROWSER', 'chromium')
    browser = getattr(pw, engine).launch(executable_path=os.getenv('CHROMIUM_PATH') or None)
    page = browser.new_page(**pw.devices['iPad (gen 7)'])
    page.goto(url+'#unterricht')
    dialog = page.get_by_role('dialog')
    for title, action, expected in [
        ('Übertrag zeigen', 'Zehn bündeln', '1 Zehner und 3 Einer'),
        ('Punktefeld zerlegen', 'Nach zehn Spalten teilen', 'links 10 Spalten'),
        ('Minuten bündeln', 'Menge in min erhöhen', '60 min'),
    ]:
        opener=page.get_by_role('button',name=title)
        opener.focus()
        page.keyboard.press('Enter')
        expect(dialog).to_be_visible()
        reveal = dialog.get_by_role('button', name='Ergebnis einblenden')
        expect(reveal).to_have_attribute('aria-expanded', 'false')
        control=dialog.get_by_role('button',name=action)
        control.focus()
        page.keyboard.press('Enter')
        assert expected in dialog.aria_snapshot()
        expect(dialog).to_contain_text(expected)
        reveal.tap()
        expect(dialog.get_by_role('button', name='Ergebnis ausblenden')).to_have_attribute('aria-expanded', 'true')
        dialog.get_by_role('button', name='Modell zurücksetzen').tap()
        expect(reveal).to_be_visible()
        if title == 'Übertrag zeigen':
            for second, total in [(1,9),(2,10),(3,11)]:
                dialog.get_by_label('Zweiter Summand').select_option(str(second))
                expect(reveal).to_be_visible()
                reveal.tap()
                expect(dialog).to_contain_text(f'8 + {second} = {total}')
        elif title == 'Punktefeld zerlegen':
            dialog.get_by_role('combobox',name='Reihen',exact=True).select_option('7')
            dialog.get_by_role('combobox',name=re.compile('^Spalten')).select_option('16')
            reveal.tap()
            expect(dialog).to_contain_text('70 + 42 = 112')
        else:
            dialog.get_by_label('Start in Minuten').select_option('119')
            dialog.get_by_role('button',name=action).tap()
            reveal.tap()
            expect(dialog).to_contain_text('2 h und 0 min')
        page.keyboard.press('Escape')
        expect(dialog).not_to_be_visible()
        expect(opener).to_be_focused()
    page.goto(url+'#division')
    page.get_by_role('button', name='Kurzrunde starten').tap()
    panel = page.locator('section').filter(has=page.get_by_role('heading', name='Kurzrunde mit drei Aufgaben'))
    x,y = map(int,re.search(r'(\d+) : (\d+)',panel.inner_text()).groups())
    field = panel.get_by_role('textbox')
    legacy={'tag':'2026-01-01','ziel':'Frühere Aufgabe','aufgabe':'9 + 1','status':'selbst','wiederholung':False}
    page.evaluate("(b)=>localStorage.setItem('mathe-kompass-lernbelege-v1',JSON.stringify([b]))",legacy)
    field.fill('0')
    panel.get_by_role('button',name='Ergebnis prüfen').tap()
    expect(panel.get_by_role('status')).to_contain_text('Zehnerstelle')
    expect(panel.get_by_role('status')).not_to_contain_text(str(x//y))
    page.reload()
    expect(field).to_have_value('0')
    expect(panel.get_by_role('button',name='Korrektur prüfen')).to_be_disabled()
    field.fill(str(x//y))
    panel.get_by_role('button',name='Korrektur prüfen').tap()
    expect(panel.get_by_role('status')).to_contain_text('Richtig gerechnet')
    record = page.evaluate("JSON.parse(localStorage.getItem('mathe-kompass-lernbelege-v1')).at(-1)")
    assert record['status']=='hilfe' and record['ersterVersuch'] is False and record['hinweise']
    records = lambda: page.evaluate("JSON.parse(localStorage.getItem('mathe-kompass-lernbelege-v1'))")
    assert len(records()) == 2 and records()[0] == legacy and record['versuche'] == 2
    panel.get_by_role('button',name='Nächste Kurzaufgabe').tap()
    for i in [1,2]:
        field.fill('999999')
        panel.get_by_role('button',name='Ergebnis prüfen').tap()
        field.fill('999998')
        panel.get_by_role('button',name='Korrektur prüfen').tap()
        panel.get_by_role('button',name='Nächste Kurzaufgabe' if i==1 else 'Runde auswerten').tap()
    panel.get_by_role('button',name='Eine ähnliche Aufgabe üben · Die Null im Quotienten eintragen').tap()
    nx,ny = map(int,re.search(r'(\d+) : (\d+)',panel.inner_text()).groups())
    assert nx//ny != x//y
    field.fill(str(nx//ny))
    panel.get_by_role('button',name='Ergebnis prüfen').tap()
    panel.get_by_role('button',name='Zur Rundenauswertung').tap()
    expect(panel).to_contain_text('Nachübung: selbstständig gelöst')
    assert len(records()) == 5 and records()[-1]['wiederholung'] and records()[0] == legacy
    page.evaluate('''() => {const k="mathe-kompass-lernbelege-v1";const a=JSON.parse(localStorage[k]);a.at(-1).tag=new Date(Date.now()-86400000).toISOString();localStorage[k]=JSON.stringify(a);}''')
    page.reload()
    panel.get_by_role('button',name=re.compile('Heute noch einmal')).tap()
    expect(panel.get_by_role('heading',name=re.compile('Tagesprobe'))).to_be_visible()
    for answer,step in [('74',2),('700',3),('9',1)]:
        page.goto(url+'#home')
        page.get_by_role('link',name='Ich komme beim Dividieren nicht weiter').click()
        page.get_by_label('Mein Ergebnis').fill(answer)
        page.get_by_role('button',name='Meinen Rechenweg prüfen').click()
        if answer=='74':
            page.get_by_role('button',name='Ich habe ohne Zehnerziffer weitergerechnet.').click()
        expect(page.locator('fieldset.div-felder legend')).to_have_text('Schritt '+str(step))
    page.reload()
    page.get_by_label('Mein Ergebnis').fill('704')
    page.get_by_role('button',name='Meinen Rechenweg prüfen').click()
    page.get_by_label('2412 : 4').fill('603')
    page.get_by_role('button',name='Ergebnis prüfen').click()
    expect(page.get_by_role('status').last).to_contain_text('603 · 4')
    page.get_by_role('button',name='Weitere Aufgabe versuchen').click()
    page.get_by_label('2848 : 4').fill('702')
    page.get_by_role('button',name='Ergebnis prüfen').click()
    page.get_by_label('2848 : 4').fill('712')
    page.get_by_role('button',name='Ergebnis prüfen').click()
    page.get_by_role('link',name='Meinen Lernstand ansehen').click()
    expect(page.get_by_text('2848 : 4 · mit Hilfe gelöst')).to_be_visible()
    expect(page.get_by_text('2412 : 4 · neue Aufgabe allein gelöst')).to_be_visible()
    page.goto(url+'#unterricht')
    page.get_by_text('Division an der Tafel aufdecken').click()
    for _ in range(3): page.get_by_role('button',name='Nächsten Schritt aufdecken').click()
    expect(page.get_by_text('1 : 4 ergibt 0',exact=False)).to_be_visible()
    page.get_by_role('button',name='Schritt zurück',exact=True).last.click()
    expect(page.get_by_text('Hole die 1 herunter. Wie oft passt 4 in 1?')).to_be_visible()
    page.goto(url+'#home')
    page.get_by_role('link',name=re.compile('Matheforscher')).click()
    thema=page.get_by_label('Thema wählen')
    def set_range(label,value):
        slider=page.get_by_role('slider',name=re.compile(label))
        slider.focus()
        slider.press('Home')
        for _ in range(value): slider.press('ArrowRight')
    def richtig():
        page.get_by_role('button',name='Antwort prüfen').click()
        expect(page.get_by_role('button',name='Antwort prüfen')).to_be_disabled()
    page.get_by_label('Mein Überschlag').select_option('2400')
    page.get_by_label('Jetzt genau ausrechnen').fill('2388')
    richtig()
    thema.select_option('1')
    page.get_by_role('button',name='Ergänzen',exact=True).click()
    page.get_by_label('Differenz').fill('205')
    page.get_by_label('Meine Strategie').select_option('Ergänzen')
    page.get_by_label('Meine Begründung').fill('Nur drei Schritte bis 602.')
    page.get_by_label('Ergebnis der neuen Aufgabe').fill('3')
    richtig()
    thema.select_option('2')
    page.get_by_label('Passende Einheit').select_option('km')
    page.get_by_label('Warum passt die Einheit?').fill('Der Weg führt ins nächste Dorf.')
    page.get_by_label('Der Weg in Metern').fill('1800')
    richtig()
    thema.select_option('3')
    set_range('Streifen verschieben',2)
    for label,value in [('Anfang in cm','2,5'),('Ende in cm','8,0'),('Länge in cm','5,5')]: page.get_by_label(label).fill(value)
    richtig()
    thema.select_option('4')
    set_range('Minuten vom Start',12)
    page.get_by_label('Minuten nach Mitternacht').fill('17')
    page.get_by_label('Gesamte Fahrt').fill('29')
    richtig()
    thema.select_option('5')
    set_range('Kleinste Zahl',50)
    set_range('Größte Zahl',149)
    richtig()
    thema.select_option('6')
    page.get_by_label('Fehlende Zehnerziffer').fill('6')
    page.get_by_label('Übertrag von den Einern').fill('1')
    richtig()
    thema.select_option('7')
    page.get_by_label('Positive Startzahl').fill('12')
    page.get_by_label('Faktor',exact=True).fill('1')
    page.get_by_label('Wann wird das Produkt').select_option('größer als 1')
    richtig()
    page.get_by_text('Fehlerdetektiv an der Tafel').click()
    for _ in range(4): page.get_by_role('button',name='Zeile aufdecken').click()
    expect(page.get_by_text('Probe: 224 + 178',exact=False)).to_be_visible()
    page.evaluate("""() => {const k='mathe-kompass-lernbelege-v1',a=JSON.parse(localStorage[k]);a.find(b=>b.ziel==='Forscheraufgabe · Überschlagen').tag='2020-01-01T12:00:00Z';localStorage[k]=JSON.stringify(a)}""")
    page.goto(url+'#home')
    page.get_by_role('link',name='Zwei-Minuten-Wiederholung ist bereit').click()
    page.get_by_role('button',name='Zwei-Minuten-Wiederholung starten').click()
    page.get_by_label('Mein Überschlag').select_option('2100')
    page.get_by_label('Jetzt genau ausrechnen').fill('2114')
    richtig()
    page.get_by_role('link',name='Zum Lernstand',exact=True).click()
    expect(page.get_by_text('302 · 7 · an einem späteren Tag selbstständig gelöst')).to_be_visible()
    browser.close()
print(engine, 'Tafelmodelle und zweiter Versuch geprüft.')
