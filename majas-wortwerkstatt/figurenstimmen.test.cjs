'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const script=fs.readFileSync(path.join(__dirname,'figurenstimmen.js'),'utf8');
const style=fs.readFileSync(path.join(__dirname,'figurenstimmen.css'),'utf8');
const b=fs.readFileSync(path.join(__dirname,'audio/figuren/baerli-mut.mp3'));
const m=fs.readFileSync(path.join(__dirname,'audio/figuren/maja-melody.mp3'));
assert(b.length>10000&&m.length>10000,'Both local audio files exist');
assert(b.subarray(0,3).toString()==='ID3'&&m.subarray(0,3).toString()==='ID3','Audio files are valid MP3 headers');
assert(/figurenstimmen\\.js\\?v=20\\d{6}[a-z]/.test(html),'Versioniertes Audio-Modul eingebunden');
assert(script.includes('player.insertAdjacentElement("afterend",link)'),'Hörtest zeigt die Hörsteuerung vor dem Figurenstimmen-Link');
assert(html.includes('figurenstimmen.css?v=20261108e'),'Audio styles integrated');
assert(html.includes("if(page==='figurenstimmen')window.MajaRealAudio.show()"),'Audio route integrated');
assert(html.includes("window.MajaRealAudio?.mount(page||'start',index,part)"),'Home and target pages have audio links');
assert(html.includes('window.MajaRealAudio?.stop()'),'Audio stops when navigating');
assert(style.includes('fs-player'),'Audio player has styles');
for(const s of html.split('<script>').slice(1).map(x=>x.split('</script>')[0]).filter(Boolean))new vm.Script(s);
new vm.Script(script);
const context={window:{},document:{querySelectorAll:()=>[]},localStorage:{getItem:()=>null,setItem(){}}};
vm.runInNewContext(script,context);
const api=context.window.MajaRealAudio;
assert.equal(api.tracks.length,2);
assert(api.tracks.some(t=>t.id==='baerli'));
assert(api.tracks.some(t=>t.id==='maja'));
assert(api.tracks.every(t=>t.text&&t.explanation&&t.answers.length===3));
assert(api.tracks.every(t=>Number.isInteger(t.right)&&t.right>=0&&t.right<3));
api.stop();
console.log('Bärli und Maja: 2 gültige MP3, Audiopfad, Syntax und Hörfragen geprüft.');